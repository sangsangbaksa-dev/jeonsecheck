export const DICT = D;

export function detectLang(saved, nav = (typeof navigator !== 'undefined' ? navigator.languages || [navigator.language] : [])) {
  if (saved && LANGS[saved]) return saved;
  for (const l of nav || []) {
    const c = String(l).slice(0, 2).toLowerCase();
    if (LANGS[c]) return c;
  }
  return 'ko';
}

let lang = 'ko';
export const getLang = () => lang;
export const setLang = (l) => { lang = LANGS[l] ? l : 'ko'; };
export const localeTag = () => LANGS[lang].locale;

export function t(key, vars = {}) {
  const s = D[lang]?.[key] ?? D.ko[key] ?? key;
  return s.replace(/(?<!\{)\{(\w+)\}(?!\})/g, (_, k) => (vars[k] ?? '') + '');
}

/** Reads the saved language (try/catch) and returns it, or null. */
export function readSavedLang(storage = (() => { try { return globalThis.localStorage; } catch { return null; } })()) {
  try {
    return storage ? storage.getItem(STORAGE_LANG_KEY) : null;
  } catch {
    return null;
  }
}

export function writeSavedLang(value, storage = (() => { try { return globalThis.localStorage; } catch { return null; } })()) {
  try {
    if (storage) storage.setItem(STORAGE_LANG_KEY, value);
  } catch {
    /* private mode or blocked storage: keep the language for this page only */
  }
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((e) => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((e) => { e.placeholder = t(e.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((e) => e.setAttribute('aria-label', t(e.dataset.i18nAria)));
  root.querySelectorAll('[data-i18n-html]').forEach((e) => { e.textContent = t(e.dataset.i18nHtml); });
}

export function langSelect(el, onChange) {
  el.innerHTML = Object.entries(LANGS).map(([k, v]) => `<option value="${k}">${v.name}</option>`).join('');
  el.value = lang;
  el.onchange = () => onChange(el.value);
}
